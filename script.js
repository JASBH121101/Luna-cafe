    el.mobileCartToggle.tabIndex = isMobile ? 0 : -1;

    el.floatingCart.classList.toggle("is-visible", show);
    el.floatingCart.setAttribute("aria-hidden", String(!show));
    el.floatingCart.tabIndex = show ? 0 : -1;
