  const keyFor = (item) =>
    `${item.id}|${item.size}|${item.milk}|${item.extraShot ? 1 : 0}|${item.flavor || ""}`;

  function defaultSize(product) {
    return product.type === "dessert"
      ? Object.keys(product.presentations)[0]
      : "regular";
  }

  function readCart() {
    try {
      const stored = JSON.parse(localStorage.getItem(CART_STORAGE_KEY) || "[]");
      if (!Array.isArray(stored)) return [];

      const result = [];

      for (const raw of stored) {
        if (!raw || !products[raw.id]) continue;

        const product = products[raw.id];
        let size = raw.size;

        if (raw.id === "brownies" && size === "slice") size = "piece";

        const validSizes = product.type === "dessert"
          ? Object.keys(product.presentations)
          : ["small", "regular", "large"];

        if (!validSizes.includes(size)) size = defaultSize(product);

        const item = {
          id: raw.id,
          size,
          milk: product.hasMilkOptions && raw.milk === "plant" ? "plant" : "whole",
          extraShot: product.type !== "dessert" && Boolean(raw.extraShot),
          qty: Math.max(1, Math.min(99, Math.floor(Number(raw.qty) || 1)))
        };

        if (product.type === "frappe") {
          item.flavor = Object.hasOwn(frappeFlavors, raw.flavor)
            ? raw.flavor
            : "chocolate";
        }

        const duplicate = result.find((entry) => keyFor(entry) === keyFor(item));

        if (duplicate) {
          duplicate.qty = Math.min(99, duplicate.qty + item.qty);
        } else {
          result.push(item);
        }
      }

      return result;
    } catch {
      return [];
    }
  }

  function saveCart() {
    writeStorage(CART_STORAGE_KEY, JSON.stringify(cart));
  }

  function subtotal() {
    return cart.reduce((sum, item) => sum + getPrice(item) * item.qty, 0);
  }

  function getPrice(item) {
    const product = products[item.id];
    if (!product) return 0;

    if (product.type === "dessert") {
      return product.presentations[item.size]
        ?? Object.values(product.presentations)[0]
        ?? 0;
    }

    let value = product.basePrice + (prices.size[item.size] || 0);

    if (product.hasMilkOptions && item.milk === "plant") {
      value += prices.plantMilk;
    }

    if (item.extraShot) value += prices.extraShot;

    return Math.max(0, Math.round(value * 100) / 100);
  }

