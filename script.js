    el.cartDrawer.setAttribute("aria-hidden", "false");
    el.cartToggle.setAttribute("aria-expanded", "true");
    el.mobileCartToggle.setAttribute("aria-expanded", "true");
    el.floatingCart.setAttribute("aria-expanded", "true");

