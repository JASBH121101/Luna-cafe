  function formatExpiry() {
    const digits = el.cardExpiry.value.replace(/\D/g, "").slice(0, 4);

    el.cardExpiry.value = digits.length > 2
      ? `${digits.slice(0, 2)}/${digits.slice(2)}`
      : digits;

    el.cardExpiry.setCustomValidity("");
  }

  function formatCvv() {
    el.cardCvv.value = el.cardCvv.value.replace(/\D/g, "").slice(0, 4);
    el.cardCvv.setCustomValidity("");
  }

  function validateDemoCard() {
    const digits = el.cardNumber.value.replace(/\D/g, "");

    el.cardholder.setCustomValidity(
      el.cardholder.value.trim().length < 2 ? t().invalidCardholder : ""
    );

    el.cardNumber.setCustomValidity(
      digits.length < 13 || digits.length > 19 ? t().invalidCardNumber : ""
    );

    const match = /^(0[1-9]|1[0-2])\/(\d{2})$/.exec(el.cardExpiry.value.trim());
    let expiryError = "";

    if (!match) {
      expiryError = t().invalidExpiry;
    } else {
      const month = Number(match[1]);
      const year = 2000 + Number(match[2]);
      const now = new Date();

      if (
        year < now.getFullYear()
        || (year === now.getFullYear() && month < now.getMonth() + 1)
      ) {
        expiryError = t().expiredCard;
      }
    }

    el.cardExpiry.setCustomValidity(expiryError);

    const cvv = el.cardCvv.value.replace(/\D/g, "");

    el.cardCvv.setCustomValidity(
      cvv.length < 3 || cvv.length > 4 ? t().invalidCvv : ""
    );

    return el.checkoutForm.reportValidity();
  }

  function saveDemoOrder(order) {
    let history = [];

    try {
      history = JSON.parse(localStorage.getItem(DEMO_ORDERS_KEY) || "[]");
      if (!Array.isArray(history)) history = [];
    } catch {
      history = [];
    }

    history.unshift(order);
    writeStorage(DEMO_ORDERS_KEY, JSON.stringify(history.slice(0, 50)));
  }

  function simulatePurchase(event) {
    event.preventDefault();

    if (!cart.length) {
      toast(t().emptyCartMessage);
      closeCheckout(false);
      return;
    }

    if (!validateDemoCard()) return;

    const total = subtotal();
    const orderId = `LC-DEMO-${Date.now().toString().slice(-8)}`;

    const items = cart.map((item) => ({
      id: item.id,
      name: t()[products[item.id].nameKey],
      options: getOptionSummary(item),
      quantity: item.qty,
      unitPrice: getPrice(item),
      lineTotal: Math.round(getPrice(item) * item.qty * 100) / 100
    }));

    saveDemoOrder({
      id: orderId,
      timestamp: new Date().toISOString(),
      total,
      currency: "USD",
      items,
      demo: true
    });

    el.orderNumber.textContent = orderId;
    el.orderTotal.textContent = money(total);

    el.checkoutForm.reset();
    clearCardErrors();
    el.checkoutFormView.hidden = true;
    el.checkoutSuccess.hidden = false;

    cart = [];
    saveCart();
    renderCart();

    el.checkoutModal.focus();
  }

