  function renderCart() {
    el.subtotal.textContent = money(subtotal());
    el.checkoutTotal.textContent = money(subtotal());

    el.cartEmpty.hidden = cart.length > 0;
    el.cartItems.hidden = cart.length === 0;

    el.localOrderButton.disabled = cart.length === 0;
    el.buyNowButton.disabled = cart.length === 0;
    el.clearButton.disabled = cart.length === 0;

    el.cartItems.innerHTML = cart.map((item) => {
      const product = products[item.id];
      const name = t()[product.nameKey];
      const key = escapeHTML(keyFor(item));
      const options = escapeHTML(getOptionSummary(item));
      const unitPrice = getPrice(item);

      return `<article class="cart-item">
        <div class="cart-item-main">
          <h3>${escapeHTML(name)}</h3>
          <p class="cart-item-details">${options}</p>
          <p class="cart-item-unit-price">${money(unitPrice)} × ${item.qty} = ${money(unitPrice * item.qty)}</p>
        </div>

        <div class="quantity-control" aria-label="${escapeHTML(name)}">
          <button type="button"
            data-cart-action="decrease"
            data-cart-key="${key}"
            aria-label="${escapeHTML(t().decreaseQuantity)}">−</button>

          <span class="quantity-value">${item.qty}</span>

          <button type="button"
            data-cart-action="increase"
            data-cart-key="${key}"
            aria-label="${escapeHTML(t().increaseQuantity)}">+</button>
        </div>

        <button class="remove-item"
          type="button"
          data-cart-action="remove"
          data-cart-key="${key}">${escapeHTML(t().removeItem)}</button>
      </article>`;
    }).join("");

    updateCartLabels();
  }

